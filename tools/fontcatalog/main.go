// Command fontcatalog writes internal/app/fonts/catalog.go: for each face,
// it asks Google Fonts' CSS API for the face's static files at the weights
// the page draws, downloads each from fonts.gstatic.com, and pins its URL,
// size and SHA-256. Run it from the repository's root to move the catalog
// to Google's current builds:
//
//	go tool fontcatalog
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"net/url"
	"os"
	"regexp"
	"strconv"
	"strings"
	"time"
)

// face is a face as the catalog lists it: its style, Serif or Sans, the
// language whose glyph forms it draws, and its family.
type face struct {
	style, forms, family string
}

// forms are the languages the faces draw, in the order the settings list
// them: Chinese and Japanese, the languages the app is written for beyond
// Latin.
var forms = []struct{ id, suffix string }{
	{"sc", "SC"},
	{"tc", "TC"},
	{"hk", "HK"},
	{"jp", "JP"},
}

// faces are the catalog's: Noto Serif, then Noto Sans, for each language.
func faces() []face {
	var out []face
	for _, style := range []string{"Serif", "Sans"} {
		for _, f := range forms {
			out = append(out, face{style, f.id, "Noto " + style + " " + f.suffix})
		}
	}
	return out
}

// weights are those the page draws: body text, and headings and strong
// text; a table header's 600 is drawn in the nearer of them.
const weights = "400;700"

// static is the host the CSS API names, whose paths the app asks of each
// of internal/app/fonts' hosts.
const static = "https://fonts.gstatic.com/"

// agent is a browser too old for WOFF2, which the CSS API answers with
// whole TrueType files, not subsets.
const agent = "Mozilla/4.0"

var (
	weightRule = regexp.MustCompile(`font-weight:\s*(\d+);`)
	srcRule    = regexp.MustCompile(`src:\s*url\(([^)]+)\)`)
)

type file struct {
	path, name   string
	weight, size int
	sha          string
}

func main() {
	out := flag.String("o", "internal/app/fonts/catalog.go", "the catalog to write")
	flag.Parse()
	var b bytes.Buffer
	b.WriteString(`// Code generated by tools/fontcatalog; DO NOT EDIT.

package fonts

// Catalog is the faces the app offers for Chinese and Japanese: Noto
// Serif, then Noto Sans, for each language's glyph forms. Each file is
// Google Fonts' static build at a weight, at its path on each of Hosts.
var Catalog = []Face{
`)
	for _, f := range faces() {
		files, err := filesOf(f)
		if err != nil {
			log.Fatalf("%s: %v", f.family, err)
		}
		fmt.Fprintf(&b, "{ID: %q, Style: %s, Forms: %q, Family: %q, Files: []File{\n",
			strings.ToLower(f.style)+"-"+f.forms, f.style, f.forms, f.family)
		for _, fl := range files {
			fmt.Fprintf(&b, "{Path: %q, Name: %q, Weight: %d, Size: %d, SHA256: %q},\n", fl.path, fl.name, fl.weight, fl.size, fl.sha)
		}
		b.WriteString("}},\n")
		log.Printf("%s: %d files", f.family, len(files))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// filesOf is f's files at the page's weights, or at the regular weight
// alone where it has no other.
func filesOf(f face) ([]file, error) {
	css, err := stylesheet(f.family + ":wght@" + weights)
	if err != nil {
		css, err = stylesheet(f.family)
	}
	if err != nil {
		return nil, err
	}
	var out []file
	for _, block := range strings.Split(css, "@font-face")[1:] {
		w, src := weightRule.FindStringSubmatch(block), srcRule.FindStringSubmatch(block)
		if w == nil || src == nil || !strings.HasPrefix(src[1], static) {
			return nil, fmt.Errorf("a face the stylesheet does not tell whole: %q", block)
		}
		weight, _ := strconv.Atoi(w[1])
		data, err := get(src[1], "")
		if err != nil {
			return nil, err
		}
		sum := sha256.Sum256(data)
		name := strings.ReplaceAll(f.family, " ", "") + "-" + w[1] + ".ttf"
		out = append(out, file{strings.TrimPrefix(src[1], static), name, weight, len(data), hex.EncodeToString(sum[:])})
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no files in %q", css)
	}
	return out, nil
}

// stylesheet is the CSS API's stylesheet for family.
func stylesheet(family string) (string, error) {
	data, err := get("https://fonts.googleapis.com/css2?family="+url.QueryEscape(family), agent)
	return string(data), err
}

// get is what u answers, asked again while the network fails.
func get(u, agent string) ([]byte, error) {
	var err error
	for try := range 5 {
		if try > 0 {
			time.Sleep(time.Duration(1<<try) * time.Second)
		}
		var req *http.Request
		if req, err = http.NewRequest(http.MethodGet, u, nil); err != nil {
			return nil, err
		}
		if agent != "" {
			req.Header.Set("User-Agent", agent)
		}
		var resp *http.Response
		if resp, err = http.DefaultClient.Do(req); err != nil {
			continue
		}
		data, rerr := io.ReadAll(resp.Body)
		resp.Body.Close()
		switch {
		case rerr != nil:
			err = rerr
		case resp.StatusCode != http.StatusOK:
			err = fmt.Errorf("%s answered %s", u, resp.Status)
			if resp.StatusCode < 500 {
				return nil, err
			}
		default:
			return data, nil
		}
	}
	return nil, err
}
